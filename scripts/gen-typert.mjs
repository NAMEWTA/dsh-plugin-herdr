// The built contract is the only method and codec registry. Build Host first.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { PANEL_METHODS } from '../lib/panel-contract.js'

const root = fileURLToPath(new URL('../', import.meta.url))
const pkg = '@namewta/dsh-plugin-herdr'
const header = '/* Generated by scripts/gen-typert.mjs; do not edit. */\n'
const host = header + `import { PANEL_DEFINITIONS, PANEL_METHODS } from './panel-contract.js'
const pkg = ${JSON.stringify(pkg)}
const codec = (name, part) => ({
  mode: 'strict',
  typeSymbol: pkg + '#' + name + ':' + part,
  create: () => PANEL_DEFINITIONS[name][part],
})
export const TYPERT = {
  package: pkg,
  face: 'host',
  schemas: [],
  invocations: PANEL_METHODS.map(name => ({
    id: pkg + '#herdr/' + name,
    service: 'herdrPanel', namespace: 'herdr', method: name,
    ...(name === 'events' ? { mode: 'stream', cancellation: { parameter: 'signal' } } : {}),
    invocation: { kind: 'direct' },
    parameters: [{ name: 'request', wire: 'request', source: 'json', codec: codec(name, 'request') }],
    result: codec(name, 'result'),
    sourceLocation: { file: 'src/host/panel/remote.ts', line: 1, column: 1 },
  })),
  model: {
    services: [{
      key: 'herdrPanel', exportName: 'HerdrPanelService',
      summary: 'Herdr profile-local control plane.', description: 'Herdr profile-local control plane.',
      jsDoc: '/** Herdr profile-local control plane. */', tags: [], types: [],
      members: PANEL_METHODS.map(name => ({
        kind: 'method', name,
        signature: name + '(request?: unknown): ' + (name === 'events' ? 'AsyncIterable<unknown>' : 'Promise<unknown>'),
        summary: name, jsDoc: '/** ' + name + ' */',
      })),
    }], events: [], objects: [],
  },
}
export const TYPERT_REMOTE = { package: TYPERT.package, descriptors: TYPERT.invocations }
export default TYPERT
`
const declarations = header + `import type { z } from 'zod'
export interface TypertInvocation {
  id: string
  service: string
  namespace: string
  method: string
  mode?: 'stream'
  cancellation?: { parameter: string }
  parameters: unknown[]
  result: { mode: string; typeSymbol: string; create: () => z.ZodType }
}
export interface TypertManifest {
  package: string
  face: 'host'
  schemas: unknown[]
  invocations: TypertInvocation[]
  model: unknown
}
export interface TypertRemoteContribution { package: string; descriptors: TypertInvocation[] }
export declare const TYPERT: TypertManifest
export declare const TYPERT_REMOTE: TypertRemoteContribution
export default TYPERT
`
for (const [file, content] of [['lib/typert.host.js', host], ['lib/typert.host.d.ts', declarations]]) {
  const path = resolve(root, file)
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== content) throw new Error(file + ' has drifted; run pnpm build')
  } else writeFileSync(path, content)
}
console.log('Typert contracts:', PANEL_METHODS.length, process.argv.includes('--check') ? 'checked' : 'written')
